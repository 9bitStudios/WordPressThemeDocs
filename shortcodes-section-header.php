<h3>Section Header Shortcode</h3>
<p>Displays a section header</p>

<h4>Shortcode:</h4>

<div class="code">
[sectionheader]
</div>

<h4>Attributes:</h4>

<b>color</b><br />
Sets the color of the text<br /><br />

<h4>Examples:</h4>
<p>The following will display a section header with black text</p>

<div class="code">
[sectionheader color="#000"]Heading 1[/sectionheader]
</div>

<p>The following will display a section header with red text</p>

<div class="code">
[sectionheader color="#f00"]Heading 1[/sectionheader]
</div>

