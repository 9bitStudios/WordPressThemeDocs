<h3>Portfolio</h3>

<p>The portfolio is configured by custom posts. You should be able to see the "Portfolio" section in the menu on the left in the WordPress dashboard.</p>

<p><img src="images/portfolio-image1.jpg" alt="Portfolio" /></p>

<p>With each post you create a portfolio item that consists of a featured image, some text content, and a button linking to the page that showcases the actual work that you did (whether that's another page on your website or an external site).</p>

<p>To create a portfolio item... </p>

<ol>
<li>Look for the Portfolio section in the menu in the WordPress Dashboard. </li>
<li>Click on Add New </li>
<li>Give your portfolio a title and add the content, images, and text that you want in the text editor field</li>
<li>In the portfolio options section(s), enter the website URL in the website URL that links to your work. You could link to your own portfolio post or you could also enter an external link (to another website) here if you wanted to as well.</li>
<li>In the portfolio options section(s), enter the preview image URL. This is the image that will be displayed on the "All portfolio items" page (see below).</li>
<li>Choose the portfolio categories that you want to use to categorize your portfolio items.</li>
</ol>

<p>Repeat this for as many portfolio items as you like.</p>

<p><img src="images/portfolio-image2.jpg" alt="Portfolio" /></p>

<p>Once you have finished creating your portfolio, the next thing you have to do is create a page to house your portfolio items. To do this, you simply follow the same steps as you do to create pages using templates...</p>

<ol>
<li>Create a page that will contain your portfolio by selecting "Pages" in the WordPress Dashboard.</li>
<li>Add a new page if you haven't already added one and give it a title (e.g. "Portfolio"). </li>
<li>You should then look for the template dropdown under the Attributes section...</li> 
<li>Select the Page - Portfolio template</li>
<li>Click the "Publish" button</li>
</ol>

<p>If you visit the page you have just created you should be able to see your portfolio item visible in the pages.</p>

<p>To further configure the portfolio (to set the number of columns, the button text, etc.) you have to set some <a href="theme-options-portfolio.php">configuration items in the theme options</a>.</p>

<p><img src="images/portfolio-theme-options.jpg" alt="Portfolio" /></p>

