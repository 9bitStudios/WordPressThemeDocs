<h3>Caption Text Shortcode</h3>
<p>Displays text in a large sectioned off area or box. Good to use as headers for various sections of a webpage.</p>

<p>Because the caption text is positioned absolutely (which means that it is not confined to boundaries within the code of the webpage), you'll likely want to set a width and height for it to fit into your content area. </p>

<h4>Shortcode:</h4>

<div class="code">
[captiontext]
</div>

<h4>Attributes:</h4>

<b>width</b><br />
Can have and value of any number. e.g. 980. Sets the width (in pixels). The default width stretches the length of a full page<br /><br />

<b>height</b><br />
Can have and value of any number. e.g. 90. Sets the height (in pixels).

<h4>Examples:</h4>

<div class="code">
[captiontext]Caption Text[/captiontext]
</div>

