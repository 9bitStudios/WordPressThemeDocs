<h3>Miscellaneous Theme Options</h3>
<p>This section of theme options contains miscellaneous additional features that you can set... </p>

<h4>Background Images</h4>
<b>Enable Different Background Images for Pages</b><br />
Check this box if you want to enable the ability to add different background images for each page.<br /><br />

<h4>Image Border Effects</h4>

<b>Enable Image Border Transitions</b><br />
Check this box if you want to enable image border transitions where borders around images change color on hover. Note that the image must have a border applied for this to be applicable<br /><br />

<b>Image Border Transition Color</b><br />
Choose the default color for the image border transitions<br /><br />

