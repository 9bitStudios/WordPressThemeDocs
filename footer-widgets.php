<h3>Using Widgets in the Footer</h3>
<p>Like the sidebar, the footer is widget ready. That is, when you log in to the WordPress dashboard and select "Widgets" you will see a location or locations to drop widgets onto the footer. The number of footer widgets varies depending on the configuration of the theme.</p>

<p>To use widgets for the footer...</p>

<ol> 
<li>Select the Appearance &rarr; Widgets option in the WordPress dashboard. This should take you to the Widgets page.</li>
<li>Expand the "Footer (#)" widget section by clicking on the drop down of the Sidebar item. By default it should be visible on the right hand side of the WordPress dashboard. # will be the particular part of the footer that the widget corresponds to. So it might be Footer 1, Footer 2, etc.</li>    
<li>From here you can drag and drop the various widgets that are available onto the widget drop section. What each widget does depends on the widget itself so feel free to experiment with it a little bit. You can move widgets on and off, up and down.</li>
<li>When you are finished adding and customizing a widget, click "Save"</li>
<li>Go to your website and refresh. You should now see the widgets that you dragged and dropped and then configured now visible on your site.</li> 
</ol>

