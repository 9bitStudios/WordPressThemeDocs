<h3>Fonts &amp; Colors Theme Options</h3>
<p>Below are some general theme options that you can configure for the fonts and colors...</p>

<h4>Custom Webfont</h4>
Below are some options for the custom webfont(s) on the site...<br /><br />

<b>Enable Custom Webfont</b><br />
Check this box if you want to set a custom webfont for the headers, title text, and other select places that the theme uses the font. If not selected, the default webfont will be used<br /><br />  

<b>Webfont</b><br />
Choose the primary embedded webfont used to style select elements on the site.<br /><br />

<h4>General Styles</h4>
Below are some general style options...<br /><br />

<b>Enable Custom General Styles</b><br />
Check this box if you want to customize the general fonts and colors of the site. Checking this box means that the values you fill out in this section will be used to style the theme. You must select this option for the rest of the items in this section to be applicable.  <br /><br />

<b>Title Text Color</b><br />
Sets the color for the title text (headers) for pages and posts at the top of the page on the site.<br /><br />

<b>Body Text Font</b><br />
Sets the font of the body text of the site.<br /><br />

<b>Body Text Size</b><br />
Sets the size of the body text of the site.<br /><br />

<b>Body Text Color</b><br />
Sets the color of the body text of the site.<br /><br />

<b>Link Color</b><br />
Sets the default color for the links on the site.<br /><br />

<b>Link Color Hover</b><br />
Sets the default color for the links on the site when the user hovers over the link.<br /><br />

<h4>Menu</h4>
Below are some style options for the menu...<br /><br />

<b>Enable Custom Menu Styles</b><br />
Check this box if you want to customize the fonts and colors of the menu. Checking this box means that the values you fill out in this section will be used to style the theme. You must select this option for the rest of the items in this section to be applicable. <br /><br /> 

<b>Menu Top-Level Link Color</b><br />
The default color for the top-level links of the menu on the site<br /><br />

<b>Menu Top-Level Link Size</b><br />
Choose the default size for the top-level links of the menu on the site<br /><br />

<b>Menu Top-Level Link Color Hover</b><br />
The default color for the top-level links of the menu on the site on hover<br /><br />

<b>Menu Sub-Level Link Color</b><br />
This sets the default color for the sub-level links of the menu on the site<br /><br />

<b>Menu Sub-Level Link Size</b><br />
Choose the default size for the sub-level links of the menu on the site<br /><br />

<b>Menu Sub-Level Link Color Hover</b><br />
This sets the default color for the sub-level links of the menu on the site on hover<br /><br />

<b>Menu Sub-Level Border Color</b><br />
This sets the default color for the sub-level background of the menu on the site (i.e. the dropdown menu border color)<br /><br />

<b>Menu Sub-Level Background Color</b><br />
This sets the default color for the sub-level background of the menu on the site (i.e. the dropdown menu background color)<br /><br />

<b>Menu Sub-Level Background Color Hover</b><br />
This sets the default color for the sub-level background of the menu on the site on hover (i.e. the dropdown menu background color on hover)<br /><br />

