<h3>Comments</h3>
<p>The comments section allows users to comment on your blog posts and also reply to other commenters on your blog posts.</p>

<p>In order to set your comments up to handle this, you need to configure your settings in the WordPress dashboard. To do this, follow the steps below...</p>

<ol>
<li>In the WordPress dashboard go to the "Settings" section and click "Discussion."</li>
<li>Under "Other Comment Settings" check the "Enable threaded (nested) comments" check box and set the dropdown to however many threads deep you want your comment replies to go.</li>
<li>Click "Save Changes" to save your settings.</li>
</ol>

<p>Please note that in order to get the "Comments are closed" text to show up in the blog post footer, you need to be sure you disable both comments and trackbacks and pingbacks to the page in addition to disabling the comments when creating or editing a post.</p>

