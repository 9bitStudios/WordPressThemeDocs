<h3>Inline Boxes Shortcode</h3>

<p>Displays boxes of text floated inline to the left or right of post and page text.</p>

<h4>Shortcode:</h4>
<div class="code">
    [inlinebox]
</div>

<h4>Attributes:</h4>

<b>orientation</b><br />
Can have the values left and right. Specifying "left" will display the image inline on the left. Specifying "right" will display the image inline on the right.<br /><br />

<h4>Examples:</h4>
<p>To display an box of text inline left...</p>

<div class="code">
[inlinebox orientation="left"]Thes text of the box goes here...[/inlinebox]
</div>

<p>To display a box of text inline right...</p>

<div class="code">
[inlinebox orientation="right"]Thes text of the box goes here...[/inlinebox]
</div>

