<h3>Google Analytics &amp; Maps Theme Options</h3>
<p>Below are some general theme options related to Google Analytics and Google maps that you can configure if you want to utilize these features...</p>

<b>Enable Google Analytics</b><br />
This is a checkbox you can check if you want to enable Google Analytics<br /><br />

<b>Google Analytics Account ID</b><br />
Enter the account ID you want to use for Google Analytics. This is only applicable if Google Analytics is enabled.<br /><br />

<b>Enable Google Maps</b><br />
This is a checkbox you can check if you want to enable Google Maps. This is only applicable if you are using the contact form that supports a Google map.<br /><br />

<b>Google Maps Marker Message</b><br />
Enter a message that you want to display on the marker for Google Maps. Important: Enter all of your message text content on the same line! Do not use the &lt;Enter&gt; key or &lt;Return&gt; key. The JavaScript used to render Google Maps will error out otherwise. You can enter HTML in this field but you want to make sure that you keep all content on the same line.<br /><br />

<b>Google Maps Coordinates</b><br />
Enter the 2 coordinates where you want to display the marker on your map separated by a comma (e.g. 21.306944,-157.858333). To find the coordinates you want you can use service such as the one at <a href="http://itouchmap.com/latlong.html">http://itouchmap.com/latlong.html</a><br /><br />

<b>Google Maps Zoom</b><br />
Enter the camera zoom of the Google maps location, 1 being furthest out, 19 being closest<br /><br />

