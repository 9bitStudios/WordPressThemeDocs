<h3>Using Widgets in the Sidebar</h3>
<p>The sidebar.php file displays some default sidebar content. However, you can create your own custom sidebar using WordPress widgets. The content that you specify there will be displayed in the sidebar instead of the default content configured with this theme. This is the recommended way that you configure your sidebar.</p>

<p>To use widgets...</p>
 
<ol>
<li>Select the Appearance &rarr; Widgets option in the WordPress dashboard. This should take you to the Widgets page.</li>
<li>Expand the "Sidebar" widget section by clicking on the drop down of the Sidebar item. By default it should be visible on the right hand side of the WordPress dashboard.</li>  
<li>From here you can drag and drop the various widgets that are available onto the widget drop section. What each widget does depends on the widget itself so feel free to experiment with it a little bit. You can move widgets on and off, up and down.</li>
<li>When you are finished adding and customizing a widget, click "Save"</li>
<li>Go to your website and go to a page that has the sidebar in it (you may have to refresh). You should now see the widgets that you dragged and dropped and then configured now visible on the sidebar of your site.</li>
</ol>

