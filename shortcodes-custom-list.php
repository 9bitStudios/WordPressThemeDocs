<h3>Custom List Shortcode</h3>
<p>Displays a custom list with custom list items utilizing icon fonts</p>

<h4>Shortcodes:</h4>

<div class="code">
[ul],[li]
</div>

<h4>Attributes:</h4>

<b>class</b><br />
Sets the class for the [li] shortcode which determinies the icon that will be displayed.<br /><br />

