<h3>Latest Posts Shortcode</h3>
<p>Displays a list of your most recent posts in list format. This shortcode is best in the sidebar or the footer.</p>

<h4>Shortcode:</h4>
<div class="code">
[latestposts] 
</div>

<h4>Attributes:</h4>

<b>limit</b><br />
Can have any numerical value. This is the number of your recent posts that you want to display.<br /><br />

<h4>Examples:</h4>
<p>The following shortcode will display the 3 latest posts...</p>

<div class="code">
[latestposts limit="3"]
</div>

