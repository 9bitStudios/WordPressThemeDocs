<h3>Blockquote Shortcode</h3>
<p>Displays a blockquote of text with author and  subtext.</p>

<h4>Shortcode:</h4>

<div class="code">
[blockquote]
</div>

<h4>Attributes:</h4>

<b>author</b><br />
Sets the author of the quote<br /><br />

<b>subtext</b><br />
Sets additional text below the author of the quote's name. Usually this can be a title of some sort such as "Vice President" or sometimes it can be used to display the years the author lived (e.g. 1881 - 1956)<br /><br />

<h4>Examples:</h4>

<p>The following will display a blockquote with author and subtext...</p>

<div class="code">
[blockqoute author="John Doe" subtext="CEO of AcmeCorp"]This is what the quote says...[/blockquote]
</div>

