<h3>Search Shortcode</h3>
<p>Displays a search form</p>

<h4>Shortcode:</h4>

<div class="code">
[search]
</div>

<h4>Attributes:</h4>

<b>theme</b><br />
Sets the style of the search form. The following values can be set...<br /><br />

<ul>
	<li>black</li>
	<li>white</li>
	<li>transparent</li>	
</ul>

<h4>Examples:</h4>
<p>The following will display a search form...</p>

<div class="code">
[search]
</div>

<p>You can also set a theme...</p>

<div class="code">
[search theme="black"]
</div>

