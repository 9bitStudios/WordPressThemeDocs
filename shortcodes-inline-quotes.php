<h3>Inline Quotes Shortcode</h3>
<p>Displays quotes of text floated inline to the left or right of post and page text.<br /><br /> 

<h4>Shortcode:</h4>
<div class="code">
    [inlinequote]
</div>

<h4>Attributes:</h4>

<b>orientation</b><br />
Can have the values left and right. Specifying "left" will display the image inline on the left. Specifying "right" will display the image inline on the right.<br /><br />

<h4>Examples:</h4>
<p>To display a quote of text inline left...</p>

<div class="code">
[inlinequote orientation="left"]Thes text of the quote goes here...[/inlinequote]
</div>

<p>To display a quote of text inline right...</p>

<div class="code">
[inlinequote orientation="right"]Thes text of the quote goes here...[/inlinequote]
</div>

