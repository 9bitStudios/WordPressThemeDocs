<h3>Author Box Shortcode</h3>
<p>Displays a box with the author's bio information in it.</p>

<h4>Shortcode:</h4>

<div class="code">
[authorbox]
</div>

<h4>Attributes:</h4>

<b>title</b><br />
Can have any text. Default value is "About the Author"<br /><br />

<b>imagepath</b><br />
Can have the path to any image<br /><br />

<h4>Examples:</h4>

<p>The following will display an author box</p>

<div class="code">
[authorbox title="About Me" imagepath="http://www.9bitstudios/image/gravatar.png"]I am the author of this post... etc.[/authorbox]
</div>

