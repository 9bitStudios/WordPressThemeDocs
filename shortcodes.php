<h3>Shortcodes</h3>
<p>One of the great things about WordPress is that it allows for the use of shortcodes. Shortcodes are basically tag words that, when put between brackets [ ] will display whatever that shortcode is set to display. For example writing the following somewhere in one of your posts... </p>

<div class="code">
[latestposts limit="3"]
</div>

<p>...might display a listing of your 3 latest blog posts.</p>

<p>What a shortcode displays depends on what is written into the theme.</p>

<p>The official WordPress shortcode documentation is available <a href="http://codex.wordpress.org/Shortcode_API" target="new">here</a></p>

<p>For a brief disclaimer/caveat about using shortcodes please see the information on <a href="shortcodes-adjusting.php">adjusting shortcodes</a></p>

