<h3>Dropcap</h3>
<p>Displays a drop cap.</p>

<h4>Shortcode:</h4>

<div class="code">
[dropcap]
</div>

<h4>Attributes:</h4>

<b>textcolor</b><br />
Can have any HTML hex color value (e.g. #336). This sets the color of the link. Be sure to include the "#" character in the value you set here as well. <br /><br />

<b>backgroundcolor</b><br />
Can have any HTML hex color value (e.g. #336). This sets the background color of the link. Be sure to include the "#" character in the value you set here as well.<br /><br /> 

<b>bordercolor</b><br />
Can have any HTML hex color value (e.g. #336). This sets the border color of the link. Be sure to include the "#" character in the value you set here as well. <br /><br />

<h4>Examples:</h4>

<p>The following will display the letter 'L' as a dropcap...</p>

<div class="code">
[dropcap textcolor="#fff" backgroundcolor="#231f74" bordercolor="#666"]L[/dropcap]orem ipsum sed und vertalis...
</div>

