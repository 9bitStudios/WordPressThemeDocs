<h3>YouTube Shortcode</h3>
<p>Display YouTube video in your pages and posts</p>

<h4>Shortcode:</h4>

<div class="code">
[youtube]
</div>

<h4>Attributes:</h4>

<b>path</b><br />
Should have the value of the path to a Youtube video taken from the embed code on the YouTube homepage.<br /><br />

<b>width</b><br />
Sets the width of the video<br /><br />

<b>height</b><br />
Sets the height of the video<br /><br />

<h4>Examples:</h4>

<p>The following will display Vimeo video...</p>

<div class="code">
[youtube path="http://www.youtube.com/embed/vhx_wocfVxA" width="640" height="360"]
</div>

