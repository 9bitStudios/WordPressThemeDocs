<h3>Staff Theme Options</h3>

<p>The staff theme options configure the items in your <a href="page-staff.php">staff</a></p>

<p>Below are the options you can set for the staff section...</p>

<b>Staff Columns</b><br />
Select the number of columns you would like to show for your staff page. Default is 3. You can also set 2 columns or 4 columns.<br /><br />

<b>Enable Pagination?</b><br />
Check this box if you want to enable pagination on your staff page. If you don't enable pagination, all of the staff items will be shown.<br /><br />

<b>Staff Items per Page</b><br />
Enter the number of staff items you want to show per page. This is only applicable if you enable pagination<br /><br />

