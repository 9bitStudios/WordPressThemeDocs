<h3>Portfolio Theme Options</h3>

<p>The portfolio theme options configure the items in your <a href="page-portfolio.php">portfolio</a></p>

<p>Below are the options you can set for the portfolio...</p>

<b>Portfolio Columns</b><br />
Select the number of columns you would like to show for your portfolio. Default is 3. You can also set 2 columns or 4 columns.<br /><br />

<b>Show Link?</b><br />
Select whether or not you want to show a link for each portfolio item (such as "Read more"). If "No" is selected, you'll just have the images and text.<br /><br />

<b>Enable Pagination?</b><br />
Check this box if you want to enable pagination in your portfolio. It is usually a good idea to choose either pagination or filtering, but not both. So if you have one disabled, it is usually best to disable the other. But you are free to experiment with it.<br /><br />

<b>Portfolio Items per Page</b><br />
Enter the number of portfolio items you want to show per page. This is only applicable if you enable pagination<br /><br />

<b>Enable Category Filter?</b><br />
Select whether or not you want the category filter menu to be visible on your portfolio home page. It is usually a good idea to choose either pagination or filtering, but not both. So if you have one disabled, it is usually best to disable the other. But you are free to experiment with it.<br /><br />

