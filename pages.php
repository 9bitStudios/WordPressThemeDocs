<h3>Pages</h3>
<p>As mentioned in the WordPress documentation found <a href="http://codex.wordpress.org/Pages" target="new">here</a>, in WordPress, you can write either posts or pages. When you're writing a regular blog entry, you write a post. Posts automatically appear in reverse chronological order on your blog's home page. Pages, on the other hand, are for content such as "About Me," "Contact Me," etc. Pages live outside of the normal blog chronology, and are often used to present information about yourself or your site that is somehow timeless -- information that is always applicable. You can use Pages to organize and manage any amount of content.</p>

<h4>Creating Pages</h4>
<p>To create a new Page, log in to your WordPress installation with sufficient admin privileges to create new articles.</p>

<ol>
<li>Create a page selecting "Pages" in the WordPress administration panel (a.k.a. the Dashboard).</li>
<li>Add a new page give it a title (e.g. "Products").</li>
<li>Keep the Template setting as Default Template and start typing in your content.</li> 
<li>Click the "Publish" button</li>
</ol>


<p>Note: You can also <a href="page-template-creation.php">create your own template pages</a> as well.</p>

