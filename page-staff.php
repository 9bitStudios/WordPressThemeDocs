<h3>Staff</h3>

<p>The staff page and pages are configured by custom posts. You should be able to see the "Staff" section in the menu on the left in the WordPress Dashboard.</p>

<p>With each post you create a staff member item that consists of a featured image, a role (e.g.  CEO, Developer, Manager, etc.), and optional contact-email, Facebook and Twitter accounts. </p>

<p>To create a staff item...</p>

<ol>
<li>Look for the Staff section in the menu in the WordPress Dashboard.</li>
<li>Click on Add New</li>
<li>Give your item a name (i.e. the staff member's name: Bob Jones, Jane Doe) and add the content that you want in the text editor field.</li>
<li>In the staff options section(s) enter the role, contact e-mail and Facebook and Twitter accounts. Note that all of these are optional. If any fields are left blank, that respective field will not be displayed.</li>
<li>In the staff options section(s), enter the staff image URL. This is the image that will be displayed on the "All staff" page (see below). </li>
<li>Click Publish.</li>
</ol>

<p>Repeat this for as many staff members as you like.</p>

<p>Once you have finished creating your staff, the next thing you have to do is create a page to house your staff post types. To do this, you simply follow the same steps as you do to create pages using templates...</p>

<ol>
<li>Create a page that will contain your staff by selecting "Pages" in the WordPress Dashboard.</li>
<li>Add a new page if you haven't already added one and give it a title (e.g. "Portfolio").</li>
<li>You should then look for the template dropdown under the Attributes section...</li>
<li>Select the Page - Staff template</li>
<li>Click the "Publish" button</li>
</ol>

<p>If you visit the page you have just created you should be able to see your portfolio item visible in the pages.</p>

