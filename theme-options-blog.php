<h3>Blog Theme Options</h3>
<p>This section is a place where you can configure options for your blog.</p>

<b>Show Tags in Post List</b><br />
Check this box if you want to display tags when viewing a list of posts<br /><br />

<b>Show Tags in Single Posts</b><br />
Check this box if you want to display tags when viewing single posts<br /><br />

<b>Show Author Box in Single Posts</b><br />
Check this box if you want to display an "About the Author" box when viewing single posts. The author avatar image and description text are set under the "Users" menu in the WordPress dashboard<br /><br />

