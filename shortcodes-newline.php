<h3>Newline Shortcode</h3>
<p>Displays content on a new line. Is used for the purposes of getting content to line up properly when needed</p>
<p>The newline shortcode will bring you to the next line much like the <a href="shortcodes-clear.php">clear shortcode</a> will, but it may not necessarily clear floated elements.  The newline shortcode essentially produces a &lt;br /&gt; HTML tag.</p>

<h4>Shortcode:</h4>

<div class="code">
[newline]
</div>
<br />

<h4>Attributes:</h4>

None<br /><br />

<h4>Examples:</h4>

<p>The following will display a gap in the content on a new line...</p>

<div class="code">
[newline]
</div>

<p>This shortcode can also be chained together. The following will display a larger gap in the content...</p>

<div class="code">
[newline] [newline]
</div>

