<h3>Header Theme Options</h3>
<p>Below are some general theme options that you can configure for the header section of the theme...</p>

<b>Top Section Left/Right</b><br />
Check the box if you want to enable a top section to put some additional content (e.g. sign in links) on the left and right. You can also use <a href="shortcodes.php">shortcodes</a> here. Note that the space here will be fairly limited. <br /><br />

Then you can enter the content that you want to put in the top section in the boxes using HTML if needed.<br /><br />

<b>Enable Logo</b><br />
Check this box if you want to enter the path to your own custom logo image. If you do not select this box, the default logo.png image file (found in the images folder of the theme) will be displayed. You can, of course, replace this logo.png file with your own custom logo image in the images to achieve the same effect without checking this box if you so choose. Just make sure that this file is named "logo.png" if you decide to go with this option.<br /><br />

<b>Logo URL</b><br />
Enter the URL to your logo image. Note: this is only applicable if you have the "Enable Logo" option checked.<br /><br />

<b>Enable Tagline</b><br />
Check this box if you want to enable the Tagline. This is the blog description that you enter in under the General Settings in the WordPress dashboard. The default value is "Just another WordPress site"<br /><br />

<b>Enable Breadcrumbs</b><br />
Check this box if you want to enable breadcrumbs on your site<br /><br />

