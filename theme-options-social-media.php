<h3>Social Media Theme Options</h3>
<p>There will also be a section somewhere within the theme that displays social media somewhere. Fortunately you can choose which icons you want to display.</p>

<b>Enable Social Media</b><br />
<p>Check this box if you want to choose your own social media below. If you do not check this box, the default values will be shown.</p>

<b>Social Media Icons</b><br />
<p>Choose the social media icons you want to display by checking the various boxes. Note that you likely will only have a limited amount of space where the social media icons are displayed. So you might want to only choose a few.</p>

<p>Below the social media icon checkboxes will be locations for you to enter the URLs to all of your various social media.</p>

