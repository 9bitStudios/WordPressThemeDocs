<h3>Theme Options</h3>

<p>What are theme options? Simply put, the theme options are essentially an admin panel where the user can enter various forms of data to change how the theme displays things. What theme options do varies quite widely from theme to theme. Below is an example of what a theme options page might look like...</p>

<p><img src="images/theme-options-fonts.png" alt="Theme Options" /></p>

<p>The theme options link will be visible and accessible in the "Appearance" box in the WordPress dashboard.</p>

