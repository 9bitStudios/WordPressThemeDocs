<h3>Accordion Shortcode</h3>
<p>The accordion allows you to display text, images, logos, or anything else in an accordion.</p>

<h4>Shortcode:</h4>

<div class="code">
[accordion], [accrodion_item]
</div>


<h4>Attributes:</h4>

<b>titletext</b><br />
This attribute is applies to the [accordion_item] shortcode. The text for the title of the accordion item is set here.<br /><br />

<h4>Examples:</h4>

<div class="code">
[accordion][accordion_item titletext="One"]Mauris quis tellus sed mi bibendum vulputate. Nam nec fermentum leo. Donec ante nisl, varius [/accordion_item] [accordion_item titletext="Two"]Nullam leo velit, placerat quis condimentum vulputate, sagittis a tellus. Belementum. [/accordion_item] [/accordion] 
</div>

