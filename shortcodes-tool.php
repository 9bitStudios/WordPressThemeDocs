<h3>Shortcodes Tool</h3>
<p>This theme has a handy tool that you can use for inserting shortcodes into your pages and posts. When you are adding or editing a page or post just look for a small "Add Shortcode" button in the Visual editor (you'll have to "show the kitchen sink" to see it) and it will appear something like the following... </p>

<p>[+]</p>  

<p>You can click on this button and you will be presented with a list of shortcodes to choose from to insert into your page or post. You will even be given all the attributes that come with the shortcode (through you will still have to fill out the fields yourself). This makes inserting shortcodes into your post easier than ever!</p>

