<h3>Icon Shortcode</h3>
<p>Displays text with an icon</p>

<h4>Shortcode:</h4>

<div class="code">
[icon]
</div>

<h4>Attributes:</h4>

<b>type</b><br />
Sets the type which determines the icon that will be displayed. The types you can choose from are below...<br /><br />

<b>class</b><br />
If you want to add some additional CSS classes to apply to the icon text (size, color, background, etc.) you can pass in additional classes here. This value is optional<br /><br />

