<h3>Vimeo Shortcode</h3>
<p>Display Vimeo video in your pages and posts</p>

<h4>Shortcode:</h4>

<div class="code">
[vimeo]
</div>

<h4>Attributes:</h4>

<b>path</b><br />
Should have the value of the path to a Vimeo video taken from the embed code on the Vimeo homepage.<br /><br />

<b>width</b><br />
Sets the width of the video<br /><br />

<b>height</b><br />
Sets the height of the video<br /><br />

<h4>Examples:</h4>

<p>The following will display Vimeo video...</p>

<div class="code">
[vimeo path="http://player.vimeo.com/video/23237102" width="600" height="264"]
</div>

