<h3>Row Shortcode</h3>
<p>Specifies a row. Used in combination with the column shortcodes. When you have a certain set of column shortcodes you want to wrap each row in a [row] shortcode</p>

<h4>Shortcode:</h4>
<div class="code">
[row]
</div>

<h4>Attributes:</h4>

None<br /><br />

<h4>Examples:</h4>

<div class="code">
[row] [half]Typi non habent claritatem[/half] [half]insitam; est usus legentis[/half][/row]
</div>

